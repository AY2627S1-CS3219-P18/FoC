import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const BASE_URL = process.env.API_BASE_URL ?? 'http://localhost:3002';

interface Recorded {
  step: string;
  role: string;
  method: string;
  path: string;
  requestInputs: string;
  status: number;
  responseBody: string;
}
const log: Recorded[] = [];

export async function call(
  step: string,
  role: string,
  token: string | undefined,
  method: string,
  path: string,
  options: { form?: Record<string, string>; headers?: Record<string, string> } = {},
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- responses are inspected loosely by the suites
): Promise<{ status: number; body: any }> {
  const headers: Record<string, string> = { ...options.headers };
  if (token) headers.Authorization = `Bearer ${token}`;
  // multipart/form-data, as the write endpoints require
  let body: FormData | undefined;
  if (options.form) {
    body = new FormData();
    for (const [k, v] of Object.entries(options.form)) body.append(k, v);
  }
  const res = await fetch(`${BASE_URL}${path}`, { method, headers, body });
  const text = await res.text();
  log.push({
    step, role, method, path,
    requestInputs: JSON.stringify({ ...(options.headers ?? {}), ...(options.form ?? {}) }),
    status: res.status,
    responseBody: text.length > 1500 ? `${text.slice(0, 1500)}... (${text.length} chars)` : text,
  });
  let parsed: unknown = text;
  try { parsed = JSON.parse(text); } catch { /* leave as text */ }
  return { status: res.status, body: parsed };
}

export function writeTranscript(name: string): void {
  const dir = resolve(import.meta.dirname, 'transcripts');
  mkdirSync(dir, { recursive: true });
  const lines = [`# ${name}`, '', `Recorded ${new Date().toISOString()} against ${BASE_URL}. Generated by the suite; not hand-edited.`, ''];
  for (const r of log) {
    lines.push(`## ${r.step}`, '', `- role: ${r.role}`, `- request: \`${r.method} ${r.path}\``, `- headers/form: \`${r.requestInputs}\``, `- status: **${r.status}**`, '- response:', '```json', r.responseBody, '```', '');
  }
  writeFileSync(resolve(dir, `${name}.md`), lines.join('\n'));
  log.length = 0;
}
